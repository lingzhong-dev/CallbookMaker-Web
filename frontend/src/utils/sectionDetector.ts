import type { LyricLine, LyricLineKind, SectionDetectOptions } from '../types/callbook'

export type SectionKind = Exclude<LyricLineKind, 'lyric'>

export const DEFAULT_SECTION_THRESHOLDS: SectionDetectOptions = {
  introThresholdMs: 6000,
  interludeThresholdMs: 8000,
  outroThresholdMs: 8000
}

export const SECTION_TITLES: Record<SectionKind, string> = {
  intro: '【前奏】',
  interlude: '【间奏】',
  outro: '【尾奏】'
}

export function getLineKind(line: Pick<LyricLine, 'kind'>): LyricLineKind {
  return line.kind ?? 'lyric'
}

export function isSectionLine(line: Pick<LyricLine, 'kind'>): boolean {
  return getLineKind(line) !== 'lyric'
}

export function sectionKindLabel(kind: LyricLineKind): string {
  switch (kind) {
    case 'intro':
      return '前奏'
    case 'interlude':
      return '间奏'
    case 'outro':
      return '尾奏'
    default:
      return '歌词'
  }
}

export function formatGapSec(ms: number): string {
  return `${(Math.max(0, ms) / 1000).toFixed(1)}s`
}

export function buildSectionSummary(kind: SectionKind, gapMs: number, intervalMs?: number): string {
  if (kind === 'intro') {
    return `前奏空档 ${formatGapSec(gapMs)}（可标进场 Call / Mix）`
  }
  if (kind === 'interlude') {
    if (intervalMs && intervalMs > gapMs) {
      return `句间间隔 ${formatGapSec(intervalMs)} · 间奏约 ${formatGapSec(gapMs)}`
    }
    return `间奏空档 ${formatGapSec(gapMs)}（可标 Mix / 喊声）`
  }
  return `尾奏空档 ${formatGapSec(gapMs)}（可标结尾 Call / 口上）`
}

function isStickySection(line: LyricLine, protectedLineIds?: Set<string>): boolean {
  if (!isSectionLine(line)) return false
  if (!line.autoGenerated) return true
  if (line.calls.length > 0 || line.customShout.trim().length > 0) return true
  if (protectedLineIds?.has(line.id)) return true
  return false
}

export interface DetectSectionsResult {
  lines: LyricLine[]
  stats: {
    intro: number
    interlude: number
    outro: number
    totalSections: number
  }
}

/**
 * 自动扫描相邻歌词时间戳与首尾空档，生成前奏 / 间奏 / 尾奏段落行。
 * 保留所有手工段落、已打 Call / 口上 / GT 高亮的段落。
 */
export function detectAndMergeSections(
  rawLines: LyricLine[],
  options?: Partial<SectionDetectOptions> & {
    totalDurationMs?: number
    protectedLineIds?: Set<string>
    onlyOutro?: boolean
  }
): DetectSectionsResult {
  const introThresholdMs = options?.introThresholdMs ?? DEFAULT_SECTION_THRESHOLDS.introThresholdMs
  const interludeThresholdMs =
    options?.interludeThresholdMs ?? DEFAULT_SECTION_THRESHOLDS.interludeThresholdMs
  const outroThresholdMs = options?.outroThresholdMs ?? DEFAULT_SECTION_THRESHOLDS.outroThresholdMs
  const totalDurationMs = options?.totalDurationMs
  const protectedLineIds = options?.protectedLineIds
  const onlyOutro = options?.onlyOutro === true

  const cloned = rawLines.map((l) => ({
    ...l,
    kind: getLineKind(l),
    calls: [...l.calls],
    text: { ...l.text }
  }))

  const lyricLines = cloned
    .filter((l) => getLineKind(l) === 'lyric')
    .sort((a, b) => a.startTimeMs - b.startTimeMs)
  const existingSections = cloned
    .filter((l) => isSectionLine(l))
    .sort((a, b) => a.startTimeMs - b.startTimeMs)

  if (lyricLines.length === 0) {
    return {
      lines: cloned.sort((a, b) => a.startTimeMs - b.startTimeMs),
      stats: {
        intro: existingSections.filter((s) => s.kind === 'intro').length,
        interlude: existingSections.filter((s) => s.kind === 'interlude').length,
        outro: existingSections.filter((s) => s.kind === 'outro').length,
        totalSections: existingSections.length
      }
    }
  }

  const stickySections = onlyOutro
    ? existingSections
    : existingSections.filter((s) => isStickySection(s, protectedLineIds))
  const generatedSections: LyricLine[] = []
  let seqCounter = 0
  const nextId = (prefix: string, ts: number) => {
    seqCounter += 1
    return `sec-${prefix}-${seqCounter}-${ts}`
  }

  if (!onlyOutro) {
    // 1. 前奏检测：第一句歌词前空档 >= introThresholdMs
    const firstLyric = lyricLines[0]
    if (firstLyric.startTimeMs >= introThresholdMs) {
      const hasStickyIntro = stickySections.some(
        (s) => s.kind === 'intro' || s.startTimeMs < firstLyric.startTimeMs
      )
      if (!hasStickyIntro) {
        generatedSections.push({
          id: nextId('intro', 0),
          startTimeMs: 0,
          endTimeMs: firstLyric.startTimeMs,
          kind: 'intro',
          autoGenerated: true,
          calls: [],
          customShout: '',
          text: {
            original: SECTION_TITLES.intro,
            translation: buildSectionSummary('intro', firstLyric.startTimeMs)
          }
        })
      }
    }

    // 2. 间奏检测：两条相邻歌词之间空的时间 >= interludeThresholdMs
    for (let i = 0; i < lyricLines.length - 1; i++) {
      const curr = lyricLines[i]
      const next = lyricLines[i + 1]
      const intervalMs = next.startTimeMs - curr.startTimeMs
      if (intervalMs <= 0) continue

      const stickyBetween = stickySections.find(
        (s) => s.startTimeMs >= curr.startTimeMs && s.startTimeMs < next.startTimeMs
      )
      const prevSecBetween = existingSections.find(
        (s) => s.kind === 'interlude' && s.startTimeMs > curr.startTimeMs && s.startTimeMs < next.startTimeMs
      )

      // 标准 LRC 解析出的 endTimeMs 通常等于 next.startTimeMs；若曾经生成过间奏也会被截断到 interlude.startTimeMs
      const hasCustomExplicitEnd =
        !prevSecBetween && curr.endTimeMs > curr.startTimeMs + 500 && curr.endTimeMs < next.startTimeMs - 300
      const measuredGapMs = hasCustomExplicitEnd ? next.startTimeMs - curr.endTimeMs : intervalMs

      if (measuredGapMs < interludeThresholdMs) {
        if (!stickyBetween && prevSecBetween && curr.endTimeMs === prevSecBetween.startTimeMs) {
          curr.endTimeMs = next.startTimeMs
        }
        continue
      }

      if (stickyBetween) {
        if (curr.endTimeMs > stickyBetween.startTimeMs && stickyBetween.startTimeMs > curr.startTimeMs) {
          curr.endTimeMs = stickyBetween.startTimeMs
        }
        continue
      }

      const breakStartMs = hasCustomExplicitEnd
        ? curr.endTimeMs
        : Math.max(
            curr.startTimeMs + 500,
            Math.min(
              next.startTimeMs - 1000,
              curr.startTimeMs + Math.min(3500, Math.round(intervalMs * 0.35))
            )
          )

      curr.endTimeMs = Math.min(curr.endTimeMs, breakStartMs)
      const breakDurationMs = Math.max(1000, next.startTimeMs - breakStartMs)

      generatedSections.push({
        id: nextId('interlude', breakStartMs),
        startTimeMs: breakStartMs,
        endTimeMs: next.startTimeMs,
        kind: 'interlude',
        autoGenerated: true,
        calls: [],
        customShout: '',
        text: {
          original: SECTION_TITLES.interlude,
          translation: buildSectionSummary(
            'interlude',
            breakDurationMs,
            hasCustomExplicitEnd ? undefined : intervalMs
          )
        }
      })
    }
  }

  // 3. 尾奏检测：仅在已知音轨真实总时长时探测末尾空档
  if (typeof totalDurationMs === 'number' && totalDurationMs > 0) {
    const lastLyric = lyricLines[lyricLines.length - 1]
    const prevOutro = existingSections.find(
      (s) => s.kind === 'outro' && s.startTimeMs >= lastLyric.startTimeMs
    )
    const rawVocalEnd = prevOutro
      ? Math.min(lastLyric.endTimeMs, prevOutro.startTimeMs)
      : lastLyric.endTimeMs
    const vocalEndMs = Math.min(
      totalDurationMs,
      Math.max(lastLyric.startTimeMs + 1000, rawVocalEnd)
    )
    const outroGapMs = totalDurationMs - vocalEndMs

    if (outroGapMs >= outroThresholdMs) {
      const hasStickyOutro = stickySections.some(
        (s) => s.kind === 'outro' || s.startTimeMs >= lastLyric.startTimeMs
      )
      if (!hasStickyOutro) {
        lastLyric.endTimeMs = vocalEndMs
        generatedSections.push({
          id: nextId('outro', vocalEndMs),
          startTimeMs: vocalEndMs,
          endTimeMs: totalDurationMs,
          kind: 'outro',
          autoGenerated: true,
          calls: [],
          customShout: '',
          text: {
            original: SECTION_TITLES.outro,
            translation: buildSectionSummary('outro', outroGapMs)
          }
        })
      }
    }
  }

  const allSections = [...stickySections, ...generatedSections]
  const combined = [...lyricLines, ...allSections].sort(
    (a, b) => a.startTimeMs - b.startTimeMs || (getLineKind(a) === 'intro' ? -1 : 1)
  )

  return {
    lines: combined,
    stats: {
      intro: allSections.filter((s) => s.kind === 'intro').length,
      interlude: allSections.filter((s) => s.kind === 'interlude').length,
      outro: allSections.filter((s) => s.kind === 'outro').length,
      totalSections: generatedSections.length
    }
  }
}

export function suggestManualSectionRange(
  kind: SectionKind,
  lines: LyricLine[],
  options: { afterLineId?: string; currentTimeMs?: number; totalDurationMs?: number }
): { startTimeMs: number; endTimeMs: number } {
  const sorted = [...lines].sort((a, b) => a.startTimeMs - b.startTimeMs)
  const firstLyric = sorted.find((l) => getLineKind(l) === 'lyric')
  const currentMs = Math.max(0, Math.round(options.currentTimeMs ?? 0))

  if (kind === 'intro') {
    const endTimeMs = firstLyric && firstLyric.startTimeMs >= 1500 ? firstLyric.startTimeMs : 8000
    return { startTimeMs: 0, endTimeMs }
  }

  if (kind === 'outro') {
    const last = sorted[sorted.length - 1]
    const startTimeMs = last ? Math.max(last.endTimeMs, last.startTimeMs + 1000) : currentMs
    const total = options.totalDurationMs ?? 0
    const endTimeMs = total > startTimeMs + 1000 ? total : startTimeMs + 8000
    return { startTimeMs, endTimeMs }
  }

  const anchorIdx = options.afterLineId
    ? sorted.findIndex((l) => l.id === options.afterLineId)
    : -1
  if (anchorIdx >= 0) {
    const anchor = sorted[anchorIdx]
    const next = sorted[anchorIdx + 1]
    if (next && next.startTimeMs - anchor.startTimeMs >= 1400) {
      const gap = next.startTimeMs - anchor.startTimeMs
      const startTimeMs = Math.round(anchor.startTimeMs + Math.min(3000, gap * 0.45))
      return { startTimeMs, endTimeMs: next.startTimeMs }
    }
    const startTimeMs = Math.max(anchor.startTimeMs + 1000, anchor.endTimeMs)
    return { startTimeMs, endTimeMs: startTimeMs + 8000 }
  }

  return { startTimeMs: currentMs, endTimeMs: currentMs + 8000 }
}
