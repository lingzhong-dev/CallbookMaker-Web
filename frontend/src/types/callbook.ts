export type CallCategory = 'downbeat' | 'upbeat' | 'build' | 'compound'
export type LyricLineKind = 'lyric' | 'intro' | 'interlude' | 'outro'

export interface SectionDetectOptions {
  introThresholdMs: number
  interludeThresholdMs: number
  outroThresholdMs: number
}

export interface CallPreset {
  id: string
  label: string // 显示名称
  color: string // 徽章主色 (Hex)
  category: CallCategory
  shortcut: string // PC端快捷键
  builtIn?: boolean
}

export interface LineCallTag {
  presetId: string
  suffix?: string // 可选倍率或备注，如 "×4"、"全员"
}

// 细粒度 GT 警报（可绑定歌词行实现行高亮与手动喊声时机提示）
export interface GtAlert {
  id: string
  triggerTimeMs: number // 触发时间戳（毫秒）
  leadBeats: number // 预警前置拍数（默认 4 拍）
  note: string // 提示文案，如 "吉他进场，4拍后进PPPH"
  targetLineId?: string // 绑定的歌词行 id（使该歌词行高亮）
  callTimingCue?: string // 编者手动输入的打 Call 时机/喊声，如 'se-no' / 'hi hi hihihihi'
}

export interface AlignedCallCue {
  id: string
  start: number // 0-based start offset in line.text.original
  end: number // 0-based exclusive end offset in line.text.original
  text: string // Displayed Call cue text aligned directly above original[start..end]
  color?: string // Optional pill accent color (Hex)
}

export interface LyricLine {
  id: string
  startTimeMs: number
  endTimeMs: number
  kind?: LyricLineKind // 默认为 'lyric'，支持 'intro' 前奏 / 'interlude' 间奏 / 'outro' 尾奏
  autoGenerated?: boolean
  calls: LineCallTag[] // 行首挂载的军Call文字标签（支持多标签组合）
  tailUpdraft?: boolean // 尾句上升气流（独立于行首军Call）
  customShout: string // 自定义喊声/Mix/口上文本
  alignedCalls?: AlignedCallCue[] // 歌词局部对位 Call 词（直接对齐显示在对应歌词上方）
  text: {
    original: string // 原文（日/中/英）
    ruby?: string // 注音 HTML（如 <ruby>夜空<rt>よぞら</rt></ruby>）
    romaji?: string // 罗马音 / 拼音
    translation?: string // 中文翻译
  }
}

export type PlatformSource =
  | 'netease'
  | 'qq'
  | 'bilibili'
  | 'lrclib'
  | 'synthetic'
  | 'local'

export interface CallProjectMeta {
  title: string
  artist: string
  platform: PlatformSource
  trackId?: string
  audioUrl: string
  bpm: number
  timeSignature: '4/4' | '3/4'
  offsetMs: number // 首拍偏移校准（毫秒）
  composer?: string // 作曲
  lyricist?: string // 作词
  vocalist?: string // 演唱
  tuner?: string // 调教
  showTuner?: boolean // 是否添加/显示调教
  editorName?: string // 编者
  editorNote?: string // 编者语
}

export interface CallProject {
  meta: CallProjectMeta
  alerts: GtAlert[] // 按 triggerTimeMs 升序排列
  lines: LyricLine[] // 按 startTimeMs 升序排列
}

export interface DisplayLayers {
  showRuby: boolean
  showRomaji: boolean
  showTranslation: boolean
}

export interface TrackSummary {
  id: string
  platform: PlatformSource
  title: string
  artist: string
  album: string
  durationMs: number
  bpm?: number | null
  hasSyncedLyrics: boolean
  hasAudioUrl: boolean
  provider: string
}

export interface SearchResponse {
  query: string
  providerUsed: string
  fallbackTriggered: boolean
  results: TrackSummary[]
}

export interface TrackDetailResponse {
  track: TrackSummary
  audioUrl: string
  rawLrc: string
  translatedLrc: string
  lines: LyricLine[]
}

export interface CallbookArchiveEntry {
  id: string
  name: string
  createdAt: number
  savedAt: number
  project: CallProject
  customPresets?: CallPreset[]
  lineCount: number
  taggedCount: number
  alertCount: number
}

export interface ArchiveSessionState {
  activeArchiveId: string | null
  hasUnsavedChanges: boolean
  hasFetchedExternalLyrics: boolean
  updatedAt?: number
}
