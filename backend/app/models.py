from typing import Dict, List, Literal, Optional
from pydantic import BaseModel, Field

PlatformType = Literal["netease", "qq", "bilibili", "lrclib", "synthetic", "local"]
LyricLineKind = Literal["lyric", "intro", "interlude", "outro"]


class SiteCopyEntryModel(BaseModel):
    key: str = Field(..., min_length=1, max_length=240)
    original: str = Field(..., min_length=1, max_length=4000)
    value: str = Field(..., max_length=4000)
    route: str = Field(default="global", max_length=64)
    updatedAt: str = Field(default="", max_length=64)


class SiteCopyDocumentModel(BaseModel):
    version: int = 1
    updatedAt: str = ""
    entries: Dict[str, SiteCopyEntryModel] = Field(default_factory=dict)


class SiteCopySaveResponse(SiteCopyDocumentModel):
    savedCount: int = 0
    projectSynced: bool = False


class LyricTextModel(BaseModel):
    original: str
    ruby: Optional[str] = None
    romaji: Optional[str] = None
    translation: Optional[str] = None


class ParsedLyricLineModel(BaseModel):
    id: str
    startTimeMs: int
    endTimeMs: int
    kind: LyricLineKind = "lyric"
    autoGenerated: bool = False
    calls: List[dict] = Field(default_factory=list)
    customShout: str = ""
    text: LyricTextModel


class TrackSummary(BaseModel):
    id: str
    platform: PlatformType
    title: str
    artist: str
    album: str = ""
    durationMs: int = 0
    bpm: Optional[int] = None
    hasSyncedLyrics: bool = False
    hasAudioUrl: bool = False
    provider: str


class TrackDetailResponse(BaseModel):
    track: TrackSummary
    audioUrl: str = ""
    rawLrc: str = ""
    translatedLrc: str = ""
    lines: List[ParsedLyricLineModel] = Field(default_factory=list)


class SearchResponse(BaseModel):
    query: str
    providerUsed: str
    fallbackTriggered: bool = False
    results: List[TrackSummary] = Field(default_factory=list)


class ParseLyricsRequest(BaseModel):
    lrc: str = Field(..., description="Primary LRC text or plain lyrics")
    translationLrc: str = Field(default="", description="Optional secondary translation LRC text")
    defaultDurationMs: int = Field(default=3000, ge=500, le=30000)
    enableRuby: bool = True
    forceJapaneseRuby: bool = False


class ParseLyricsResponse(BaseModel):
    isJapanese: bool
    lines: List[ParsedLyricLineModel]


class RubyRequest(BaseModel):
    text: str
    forceJapanese: bool = True


class RubyResponse(BaseModel):
    original: str
    ruby: str
    romaji: str
    isJapanese: bool


class GatewayConfigureRequest(BaseModel):
    neteaseCookie: str = Field(default="", max_length=12000)
    gatewayUrl: str = Field(default="http://127.0.0.1:3000", max_length=256)
    searchPath: str = Field(default="/search", max_length=128)
    lyricPath: str = Field(default="/lyric", max_length=128)
    urlPath: str = Field(default="/song/url", max_length=128)
    autoStart: bool = True
    clearCookie: bool = False


class GatewayStatusResponse(BaseModel):
    gatewayUrl: str
    gatewayOnline: bool
    customProxyEnabled: bool
    cookieConfigured: bool
    cookieMasked: str = ""
    managedByBackend: bool = False
    pid: Optional[int] = None
    canSpawnLocal: bool = False
    nodeAvailable: bool = False
    packageAvailable: bool = False
    neteaseAccount: Optional[str] = None
    message: str = ""
